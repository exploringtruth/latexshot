#!/usr/bin/env python3
"""Assemble a pinned runtime prototype; does not qualify it for public release."""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import platform
import shutil
import subprocess
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def fetch(entry, cache):
    path = cache / entry.get('filename', entry.get('name'))
    if path.exists() and path.stat().st_size == entry['bytes'] and digest(path) == entry['sha256']:
        return path
    temporary = path.with_suffix(path.suffix + '.download')
    if not entry['url'].startswith('https://'):
        raise ValueError('Only locked HTTPS artifacts are accepted')
    try:
        urllib.request.urlretrieve(entry['url'], temporary)
        if temporary.stat().st_size != entry['bytes'] or digest(temporary) != entry['sha256']:
            raise ValueError('Artifact checksum mismatch: ' + path.name)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)
    return path


def assemble(destination, cache, lock_path):
    if platform.system() != 'Darwin' or platform.machine() != 'arm64':
        raise ValueError('Use an Apple silicon Mac')
    if destination.exists():
        raise ValueError('Use a new destination; existing runtime trees are never overwritten')
    lock = json.loads(lock_path.read_text())
    if digest(ROOT / 'benchmarks/requirements-lock.txt') != lock['requirements_sha256']:
        raise ValueError('Recognition requirements changed; review and repin the prototype lock')
    destination.mkdir(parents=True)
    cache.mkdir(parents=True, exist_ok=True)
    archive = fetch(lock['python'], cache)
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        list(pool.map(lambda entry: fetch(entry, cache), lock['wheels']))
    with tarfile.open(archive) as source:
        source.extractall(destination, filter='data')
    runtime = destination / 'RecognitionRuntime'
    (destination / 'python').rename(runtime)
    requirements = destination / 'requirements-hashed.txt'
    requirements.write_text(''.join(f"{entry['name']}=={entry['version']} --hash=sha256:{entry['sha256']}\n"
                                    for entry in lock['wheels']))
    subprocess.run(['sandbox-exec', '-p', '(version 1)(allow default)(deny network*)',
                    str(runtime / 'bin/python3'), '-I', '-B', '-m', 'pip', 'install',
                    '--no-compile', '--no-deps', '--no-index', '--find-links', str(cache),
                    '--require-hashes', '-r', str(requirements)], check=True)
    # Console launchers generated by pip contain the assembly path. The app only
    # uses python3 -I -B. Keep that runtime entry point, not build-time tools.
    for path in (runtime / 'bin').iterdir():
        if path.name not in ('python', 'python3', 'python3.12'):
            if path.is_dir() and not path.is_symlink():
                shutil.rmtree(path)
            else:
                path.unlink()
    record = {'status': 'PROTOTYPE_NOT_RELEASE_QUALIFIED', 'build_prefix': str(runtime),
              'lock_sha256': digest(lock_path), 'python_artifact_sha256': lock['python']['sha256'],
              'wheel_count': len(lock['wheels']), 'wheel_bytes': sum(entry['bytes'] for entry in lock['wheels'])}
    (runtime / 'assembly.json').write_text(json.dumps(record, indent=2) + '\n')
    print('Prototype assembled:', runtime)
    print('Move RecognitionRuntime outside this destination before verifying relocation.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    parser.add_argument('--cache', required=True, type=Path)
    parser.add_argument('--lock', type=Path, default=ROOT / 'docs/runtime/prototype-lock.json')
    args = parser.parse_args()
    assemble(args.destination.resolve(), args.cache.resolve(), args.lock.resolve())
